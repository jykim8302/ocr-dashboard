# 라즈베리파이 피코에 넣는 파일 (1/2)
# 이 파일은 피코가 켜질 때 딱 한 번 실행됩니다.
#
# 피코를 두 가지로 동시에 동작하게 만듭니다.
#   1. USB 마우스 (HID)
#   2. PC 와 데이터를 주고받는 시리얼 포트
#
# console=False 로 두는 것이 중요합니다. True 로 두면 COM 포트가 두 개
# 생기는데, 둘 중 어느 것이 데이터 포트인지 겉으로는 구별되지 않습니다.
# 콘솔 포트를 골라 연결하면 보내기는 성공했다고 나오는데 마우스는 꿈쩍도
# 하지 않습니다. 포트를 하나만 만들어 그런 일이 없게 합니다.
#
# 마우스는 두 개를 만듭니다.
#   - 기본 마우스 : 한 번에 127 까지만 움직일 수 있는 보통 마우스
#   - 큰 걸음 마우스 : 한 번에 32767 까지 움직일 수 있는 마우스
#
# 보통 USB 마우스는 정해진 간격(대개 8밀리초)마다 한 번씩만 보고할 수
# 있습니다. 그 한 번에 127 밖에 못 담으면 빠르게 움직인 구간에서 보낼
# 양이 밀리기 시작하고, 밀린 양은 그대로 지연이 됩니다. 지연이 쌓이는
# 동안에는 누르기와 놓기 사이도 같이 늘어나서 클릭이 길어집니다.
# 한 번에 32767 까지 담을 수 있으면 밀릴 일이 없어집니다.
#
# 기본 마우스를 함께 남겨 두는 이유: code.py 를 아직 옛 것으로 두었더라도
# 그 쪽은 기본 마우스를 찾아 쓰게 되어 전처럼은 동작합니다.

import usb_cdc
import usb_hid

usb_cdc.enable(console=False, data=True)

# 한 번에 32767 까지 움직이는 마우스의 HID 설명서.
# 보고 한 묶음은 6바이트입니다 -> [버튼, 가로 하위, 가로 상위,
#                                 세로 하위, 세로 상위, 휠]
FAST_MOUSE_DESCRIPTOR = bytes((
    0x05, 0x01,        # 쓰임새 묶음: 일반 책상용 장치
    0x09, 0x02,        # 쓰임새: 마우스
    0xA1, 0x01,        # 묶음 시작 (프로그램)
    0x09, 0x01,        #   쓰임새: 포인터
    0xA1, 0x00,        #   묶음 시작 (물리)
    0x85, 0x04,        #     보고 번호 4
    0x05, 0x09,        #     쓰임새 묶음: 버튼
    0x19, 0x01,        #     버튼 1번부터
    0x29, 0x05,        #     버튼 5번까지
    0x15, 0x00,        #     값은 0 부터
    0x25, 0x01,        #     값은 1 까지
    0x75, 0x01,        #     한 칸은 1비트
    0x95, 0x05,        #     다섯 칸
    0x81, 0x02,        #     입력 (자료, 값, 절대)
    0x75, 0x03,        #     한 칸은 3비트
    0x95, 0x01,        #     한 칸
    0x81, 0x01,        #     입력 (고정) - 남는 자리 메우기
    0x05, 0x01,        #     쓰임새 묶음: 일반 책상용 장치
    0x09, 0x30,        #     쓰임새: 가로
    0x09, 0x31,        #     쓰임새: 세로
    0x16, 0x01, 0x80,  #     값은 -32767 부터
    0x26, 0xFF, 0x7F,  #     값은 32767 까지
    0x75, 0x10,        #     한 칸은 16비트
    0x95, 0x02,        #     두 칸
    0x81, 0x06,        #     입력 (자료, 값, 상대)
    0x09, 0x38,        #     쓰임새: 휠
    0x15, 0x81,        #     값은 -127 부터
    0x25, 0x7F,        #     값은 127 까지
    0x75, 0x08,        #     한 칸은 8비트
    0x95, 0x01,        #     한 칸
    0x81, 0x06,        #     입력 (자료, 값, 상대)
    0xC0,              #   묶음 끝
    0xC0,              # 묶음 끝
))

try:
    fast_mouse = usb_hid.Device(
        report_descriptor=FAST_MOUSE_DESCRIPTOR,
        usage_page=0x01,
        usage=0x02,
        report_ids=(4,),
        in_report_lengths=(6,),
        out_report_lengths=(0,),
    )
    # 기본 마우스를 먼저 적는다. 옛 code.py 는 먼저 찾은 마우스를 쓰므로
    # 이렇게 두면 파일을 하나만 바꿔 놓았을 때도 전처럼 동작한다.
    usb_hid.enable((usb_hid.Device.MOUSE, fast_mouse))
except Exception:
    # 설명서를 받아 주지 않는 옛 CircuitPython 이면 기본 마우스만 쓴다.
    # 여기서 멈추면 마우스가 아예 안 생기므로 반드시 되돌려 둔다.
    try:
        usb_hid.enable((usb_hid.Device.MOUSE,))
    except Exception:
        pass
